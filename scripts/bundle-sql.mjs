// Embeds the SQL migrations into src/lib/setup/sql.generated.ts so the /setup page can apply
// them on Vercel without reading files at runtime. Runs automatically before `npm run build`.
import fs from "node:fs";

const files = [
  "supabase/migrations/0001_schema.sql",
  "supabase/migrations/0002_rls.sql",
  "supabase/migrations/0003_storage.sql",
  "supabase/seed.sql",
];
const entries = files.map((f) => `  { file: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(f, "utf8"))} },`);
fs.writeFileSync(
  "src/lib/setup/sql.generated.ts",
  `// Generated by scripts/bundle-sql.mjs from supabase/*.sql. Do not edit by hand.\nexport const SETUP_SQL: { file: string; sql: string }[] = [\n${entries.join("\n")}\n];\n`,
);
console.log(`bundled ${files.length} SQL files`);
